<?php
/**
 * Writes a bash script that installs (or removes) the single-file Breakwater mu-plugin on a
 * WordPress site. Made for CaptainCore, which pipes a script into each site's web root:
 *
 *   php bin/mu-deploy-script.php --mode=monitor            # → dist/deploy-mu.sh
 *   captaincore ssh site1 site2 … --script=deploy-mu.sh --parallel=20 --label
 *
 * Options:
 *   --mode=<auto|monitor|protect|off>  Mode for sites that have never had one (default: leave it,
 *                                      which means auto: monitor while CleanTalk is active).
 *   --force-mode                       Set --mode even where the site already has a mode.
 *   --remove                           Remove the mu-plugin instead (settings and log are kept).
 *   --out=<file>                       Default dist/deploy-mu.sh (or dist/remove-mu.sh).
 *
 * The script skips sites that aren't WordPress, run PHP older than 8.1 (the file would not
 * parse), or have the regular plugin active. It writes the file atomically, checks its sha256,
 * loads WordPress to confirm Breakwater boots, and takes the file out again if it doesn't. Each
 * site prints one line: BREAKWATER|<home>|<result>|<details>.
 */

$root    = dirname( __DIR__ );
$options = getopt( '', [ 'mode:', 'force-mode', 'remove', 'out:' ] );
$remove  = isset( $options['remove'] );
$mode    = (string) ( $options['mode'] ?? '' );
if ( '' !== $mode && ! in_array( $mode, [ 'auto', 'monitor', 'protect', 'off' ], true ) ) {
	fwrite( STDERR, "Unknown mode: $mode\n" );
	exit( 1 );
}
$out = (string) ( $options['out'] ?? $root . '/dist/' . ( $remove ? 'remove-mu.sh' : 'deploy-mu.sh' ) );

$common = <<<'BASH'
#!/bin/bash
# Generated by Breakwater's bin/mu-deploy-script.php. Runs in a WordPress site's web root.
if [ ! -f wp-config.php ]; then
    echo "BREAKWATER|$(pwd)|skip|not a WordPress root"
    exit 0
fi
WP="wp --skip-themes"
home=$($WP --skip-plugins option get home 2>/dev/null)
mu_dir=$($WP --skip-plugins eval 'echo WPMU_PLUGIN_DIR;' 2>/dev/null)
mu_dir=${mu_dir:-wp-content/mu-plugins}
target="$mu_dir/breakwater.php"

BASH;

if ( $remove ) {
	$script = $common . <<<'BASH'
if [ ! -f "$target" ]; then
    echo "BREAKWATER|$home|skip|not installed"
    exit 0
fi
rm -f "$target"
echo "BREAKWATER|$home|removed|settings and log kept"

BASH;
} else {
	$build = $root . '/dist/breakwater.php';
	passthru( 'php ' . escapeshellarg( $root . '/bin/build-mu-plugin.php' ) . ' ' . escapeshellarg( $build ), $status );
	if ( 0 !== $status ) {
		exit( 1 );
	}
	$code    = file_get_contents( $build );
	$sha     = hash( 'sha256', $code );
	$version = preg_match( '/^ \* Version:\s+(\S+)/m', $code, $m ) ? $m[1] : '?';
	if ( str_contains( $code, 'BREAKWATER_MU_PLUGIN_EOF' ) ) {
		fwrite( STDERR, "The build contains the heredoc delimiter.\n" );
		exit( 1 );
	}
	$set_mode = '';
	if ( '' !== $mode ) {
		$set_mode = isset( $options['force-mode'] )
			? "\$WP option update breakwater '{\"mode\":\"$mode\"}' --format=json >/dev/null 2>&1\n"
			: "\$WP option add breakwater '{\"mode\":\"$mode\"}' --format=json >/dev/null 2>&1\n";
	}
	$script = $common . <<<BASH
php_id=\$(\$WP --skip-plugins eval 'echo PHP_VERSION_ID;' 2>/dev/null)
if [ -z "\$php_id" ] || [ "\$php_id" -lt 80100 ]; then
    echo "BREAKWATER|\$home|skip|PHP \${php_id:-unknown} is older than 8.1"
    exit 0
fi
if \$WP --skip-plugins plugin is-active breakwater >/dev/null 2>&1; then
    echo "BREAKWATER|\$home|skip|the regular plugin is active"
    exit 0
fi
mkdir -p "\$mu_dir"
tmp="\$mu_dir/.breakwater.php.tmp"
cat > "\$tmp" <<'BREAKWATER_MU_PLUGIN_EOF'
$code
BREAKWATER_MU_PLUGIN_EOF
# The heredoc adds one trailing newline; strip it so the checksum matches the build.
php -r '\$f = \$argv[1]; file_put_contents( \$f, substr( file_get_contents( \$f ), 0, -1 ) );' "\$tmp"
if [ "\$(php -r 'echo hash_file( "sha256", \$argv[1] );' "\$tmp")" != "$sha" ]; then
    rm -f "\$tmp"
    echo "BREAKWATER|\$home|failed|checksum mismatch"
    exit 0
fi
previous=""
[ -f "\$target" ] && previous=\$(grep -m1 ' \\* Version:' "\$target" | awk '{print \$NF}')
mv -f "\$tmp" "\$target"
{$set_mode}status=\$(\$WP eval 'echo defined( "BREAKWATER_FILE" ) && class_exists( "Breakwater\\\\Plugin", false ) ? Breakwater\\Plugin::VERSION . " " . Breakwater\\Plugin::mode()->value : "not-loaded";' 2>/dev/null | tail -1)
case "\$status" in
    $version\ *)
        echo "BREAKWATER|\$home|installed|$version \${status#* }\${previous:+ (was \$previous)}"
        ;;
    *)
        rm -f "\$target"
        echo "BREAKWATER|\$home|failed|did not load (\${status:-fatal}), removed"
        ;;
esac

BASH;
}

if ( ! is_dir( dirname( $out ) ) ) {
	mkdir( dirname( $out ), 0755, true );
}
file_put_contents( $out, $script );
chmod( $out, 0755 );
exec( 'bash -n ' . escapeshellarg( $out ) . ' 2>&1', $lint, $status );
if ( 0 !== $status ) {
	fwrite( STDERR, implode( "\n", $lint ) . "\n" );
	exit( 1 );
}
printf( "Wrote %s (%s%s), %s KB\n", $out, $remove ? 'remove' : 'install Breakwater ' . $version, '' !== $mode && ! $remove ? ', mode ' . $mode . ( isset( $options['force-mode'] ) ? ' forced' : ' if unset' ) : '', number_format( filesize( $out ) / 1024, 1 ) );
