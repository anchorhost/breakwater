<?php
/**
 * Builds Breakwater as one self-contained mu-plugin file: every class from src/ in bracketed
 * namespace blocks, and the script, admin stylesheet, mark and disposable-domain list embedded
 * in a Bundle class (see src/Assets.php). Drop the file in wp-content/mu-plugins/ and it runs.
 *
 * Usage: php bin/build-mu-plugin.php [out-file]     (default dist/breakwater.php)
 *
 * The file needs PHP 8.1+ just to parse, so it can't show a notice on older PHP the way the
 * regular plugin does. bin/mu-deploy-script.php checks the version before installing it.
 */

$root = dirname( __DIR__ );
$out  = $argv[1] ?? $root . '/dist/breakwater.php';

// Dependency order: enums and value objects first, the Adapter base before every adapter,
// the registry after them. Every file in src/ must be listed (checked below).
$order = [
	'Mode', 'Proof', 'Verdict', 'Reputation', 'Submission', 'Challenge', 'Log', 'Trust', 'Feedback',
	'Checker', 'Guard', 'Delivery', 'Release', 'Digest', 'Assets', 'Front', 'Admin', 'Cli', 'Plugin',
	'Adapters/Adapter',
];
$adapters = array_map( fn ( $f ) => 'Adapters/' . basename( $f, '.php' ), glob( $root . '/src/Adapters/*.php' ) );
$adapters = array_values( array_diff( $adapters, [ 'Adapters/Adapter', 'Adapters/Registry' ] ) );
sort( $adapters );
$order    = array_merge( $order, $adapters, [ 'Adapters/Registry' ] );

// Regular plugin only. The fleet's mu-plugin is updated by redeploying it, never by itself.
$excluded = [ 'Updater' ];

$present = array_map( fn ( $f ) => substr( $f, strlen( $root . '/src/' ), -4 ), array_merge( glob( $root . '/src/*.php' ), glob( $root . '/src/Adapters/*.php' ) ) );
$missing = array_diff( $present, $order, $excluded );
if ( $missing ) {
	fwrite( STDERR, 'Not in the build order: ' . implode( ', ', $missing ) . "\n" );
	exit( 1 );
}

$version = preg_match( "/const VERSION\s*=\s*'([^']+)'/", file_get_contents( $root . '/src/Plugin.php' ), $m ) ? $m[1] : '0.0.0';
$commit  = trim( (string) shell_exec( 'git -C ' . escapeshellarg( $root ) . ' rev-parse --short HEAD 2>/dev/null' ) );
$dirty   = trim( (string) shell_exec( 'git -C ' . escapeshellarg( $root ) . ' status --porcelain -- src assets data 2>/dev/null' ) ) !== '' ? '+changes' : '';

$blocks = [];
foreach ( $order as $name ) {
	$code = file_get_contents( $root . '/src/' . $name . '.php' );
	if ( ! preg_match( '/^namespace\s+([^;]+);/m', $code, $ns ) ) {
		fwrite( STDERR, "No namespace in src/$name.php\n" );
		exit( 1 );
	}
	$code     = preg_replace( '/^<\?php\s*/', '', $code );
	$code     = preg_replace( '/^declare\(strict_types=1\);\s*/m', '', $code );
	$code     = preg_replace( '/^namespace\s+[^;]+;\s*/m', '', $code );
	$blocks[] = "// src/$name.php\nnamespace {$ns[1]} {\n\n" . rtrim( $code ) . "\n}\n";
}

// The assets, as nowdoc strings. A delimiter that appears in its content would end it early.
$assets = [
	'SCRIPT'     => 'assets/breakwater.js',
	'ADMIN_CSS'  => 'assets/admin.css',
	'MARK'       => 'assets/mark.svg',
	'DISPOSABLE' => 'data/disposable-domains.txt',
];
$consts = '';
foreach ( $assets as $const => $file ) {
	$content   = rtrim( file_get_contents( $root . '/' . $file ) );
	$delimiter = 'BREAKWATER_' . $const;
	if ( str_contains( $content, $delimiter ) ) {
		fwrite( STDERR, "$file contains $delimiter\n" );
		exit( 1 );
	}
	$consts .= "\n\t/** $file */\n\tpublic const $const = <<<'$delimiter'\n$content\n$delimiter;\n";
}
$blocks[] = "// Embedded assets, read through Breakwater\\Assets.\nnamespace Breakwater {\n\nfinal class Bundle {\n$consts}\n}\n";

$blocks[] = <<<'PHP'
// Bootstrap.
namespace {

defined( 'ABSPATH' ) || exit;

// Loaded once even when the regular plugin is also installed: the mu-plugin loads first and wins.
if ( ! defined( 'BREAKWATER_FILE' ) ) {
	define( 'BREAKWATER_FILE', __FILE__ );
	Breakwater\Plugin::boot( __FILE__ );
}
}
PHP;

$header = <<<HEADER
<?php
/**
 * Plugin Name:       Breakwater
 * Plugin URI:        https://github.com/anchorhost/breakwater
 * Description:       Spam protection for comments, registrations and contact forms. Single-file mu-plugin build.
 * Version:           $version
 * Requires PHP:      8.1
 * Author:            Anchor Hosting
 * Author URI:        https://anchor.host
 * License:           MIT
 *
 * Generated by bin/build-mu-plugin.php from {$commit}{$dirty}. Do not edit: change src/ and rebuild.
 * Needs PHP 8.1+ to parse at all; bin/mu-deploy-script.php checks before installing.
 */

declare(strict_types=1);


HEADER;

if ( ! is_dir( dirname( $out ) ) ) {
	mkdir( dirname( $out ), 0755, true );
}
file_put_contents( $out, $header . implode( "\n", $blocks ) );

exec( 'php -l ' . escapeshellarg( $out ) . ' 2>&1', $lint, $status );
if ( 0 !== $status ) {
	fwrite( STDERR, implode( "\n", $lint ) . "\n" );
	exit( 1 );
}
printf( "Built %s: Breakwater %s (%s%s), %d classes, %s KB\n", $out, $version, $commit ?: 'no git', $dirty, count( $order ) + 1, number_format( filesize( $out ) / 1024, 1 ) );
